/** Build { holidays: Map<iso,name>, workdays: Map<iso,reason>, weekend: number[] } for a country. */
// eslint-disable-next-line no-unused-vars
function jwmBuildCalendar(country, fromYear, toYear) {
  const c = JWM_HOLIDAYS[country] || JWM_HOLIDAYS.US;
  const holidays = new Map(Object.entries(c.dates || {}));
  if (typeof c.generate === "function") {
    for (let y = fromYear; y <= toYear; y++) {
      for (const [k, v] of Object.entries(c.generate(y))) holidays.set(k, v);
    }
  }
  const workdays = new Map(Object.entries(c.workdays || {}));
  return { holidays, workdays, weekend: c.weekend || [0, 6], lang: c.lang || "en" };
}
